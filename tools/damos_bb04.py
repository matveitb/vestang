def axis_ok(d, objs, idx, sig):
    """Проверка, что ось в этом файле та же по смыслу (значения точек)."""
    o = objs[idx] if idx < len(objs) else None
    if o is None or o.what != 'ось' or o.data is None:
        return False
    v = [x - 65536 if x > 32767 and o.etype in (2, 3) else x for x in o.values(d)]
    if sig == 'N':
        return 500 <= v[0] and v[-1] <= 13000 and v == sorted(v)
    if sig in ('TCOOL', 'TAIR'):
        # −50…130 °C в единицах 1/128, по возрастанию, кратно 0,5 °C
        return v == sorted(v) and -6400 <= v[0] < 0 and v[-1] <= 16640 and all(x % 64 == 0 for x in v)
    if sig == 'GEAR':
        return v == list(range(len(v)))
    if sig == 'PEDAL':
        return v[0] == 0 and v[-1] == 12800
    if sig == 'LOAD':
        return v == sorted(v) and v[0] > 0 and v[-1] <= 9000
    if sig == 'VSPEED':
        return v == sorted(v) and v[0] == 0 and v[-1] <= 16000
    return v == sorted(v)

def ram_found(d):
    """Переменные RAM, подтверждённые литералом (код может быть сдвинут, как у BB02)."""
    import struct
    out = []
    for a, *rest, p in RAM:
        if any(struct.unpack_from('<I', d, o)[0] == a for o in range(p - 0x400, p + 0x400, 4)):
            out.append((a, *rest))
    return out
